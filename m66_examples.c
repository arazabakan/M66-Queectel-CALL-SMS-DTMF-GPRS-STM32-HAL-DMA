void Example_M66_HTTP_POST(void)
{
    static const uint8_t json[] = "{\"device\":\"M66\",\"value\":23}";
    M66_Status status;
    int http_status = 0;
    int32_t response_length = 0;
    uint8_t response[512];
    size_t received = 0U;

    status = M66_HTTPSetParameter(&hm66, "Content-Type", "application/json");
    M66_CheckResult("Set HTTP Content-Type", status);

    status = M66_HTTPPost(&hm66,
                          "http://example.com/api/telemetry",
                          json,
                          sizeof(json) - 1U,
                          60000U,
                          &http_status,
                          &response_length);
    M66_CheckResult("HTTP POST JSON", status);
    printf("HTTP status=%d, response length=%ld\r\n",
           http_status, (long)response_length);
    if (status != M66_OK) return;

    status = M66_HTTPRead(&hm66, response, sizeof(response), &received, 30000U);
    M66_CheckResult("Read HTTP POST response", status);
    if (status == M66_OK) {
        printf("HTTP response bytes=%lu\r\n", (unsigned long)received);
    }
}

