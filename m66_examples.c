/* 8. TCP client: connect, send, receive binary-safe data, close.               */
/* ------------------------------------------------------------------------- */
void Example_M66_TCP(void)
{
    static const uint8_t request[] = "GET / HTTP/1.0\r\nHost: example.com\r\n\r\n";
    uint8_t rx[256];
    size_t received = 0U;
    M66_Status status;

    status = M66_SocketOpen(&hm66, 0U, "TCP", "example.com", 80U, 60000U);
    M66_CheckResult("Open TCP socket", status);
    if (status != M66_OK) return;

    status = M66_SocketSend(&hm66, 0U, request,
                            (uint16_t)(sizeof(request) - 1U), 30000U);
    M66_CheckResult("Send TCP request", status);

    /* Call when the modem reports incoming data; timeout depends on server. */
    status = M66_SocketReadData(&hm66, 0U, sizeof(rx), rx, sizeof(rx),
                                &received, 30000U);
    M66_CheckResult("Read TCP response", status);
    if (status == M66_OK) {
        printf("TCP bytes received: %lu\r\n", (unsigned long)received);
        /* Binary payload is not necessarily NUL-terminated; do not printf as %s. */
        /* Process rx[0..received-1] here. */
    }

    M66_CheckResult("Close TCP socket", M66_SocketClose(&hm66, 0U));
}

