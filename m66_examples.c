/* 12. MQTT publish/subscribe example.                                         */
/* ------------------------------------------------------------------------- */
void Example_M66_MQTT(void)
{
    static const uint8_t payload[] = "{\"temperature\":24.5}";
    M66_Status status;

    status = M66_MQTTOpen(&hm66, 0U, "broker.example.com", 1883U, 60000U);
    M66_CheckResult("Open MQTT connection", status);
    if (status != M66_OK) return;

    status = M66_MQTTConnect(&hm66, 0U, "stm32f4-m66-demo", "", "", 60000U);
    M66_CheckResult("MQTT CONNECT", status);
    if (status != M66_OK) {
        (void)M66_MQTTClose(&hm66, 0U, 10000U);
        return;
    }

    M66_CheckResult("MQTT keepalive", M66_MQTTSetKeepAlive(&hm66, 0U, 60U));
    M66_CheckResult("MQTT subscribe", M66_MQTTSubscribe(&hm66, 0U, 1U,
                                                        "devices/m66/command", 0U, 30000U));
    M66_CheckResult("MQTT publish", M66_MQTTPublish(&hm66, 0U, 2U, 0U, 0U,
                                                      "devices/m66/telemetry",
                                                      payload, sizeof(payload) - 1U,
                                                      30000U));

    /* Incoming MQTT data is delivered through the driver's event callback. */
    /* M66_EV_MQTT_MESSAGE handling should copy/process the topic and payload. */

    M66_CheckResult("MQTT disconnect", M66_MQTTDisconnect(&hm66, 0U, 30000U));
    M66_CheckResult("MQTT close", M66_MQTTClose(&hm66, 0U, 10000U));
}

