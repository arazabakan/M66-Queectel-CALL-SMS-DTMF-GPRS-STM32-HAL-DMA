    if (status == M66_OK) printf("IMEI: %s\r\n", text);

    status = M66_GetIMSI(&hm66, text, sizeof(text));
    M66_CheckResult("IMSI", status);
    if (status == M66_OK) printf("IMSI: %s\r\n", text);

    status = M66_GetICCID(&hm66, text, sizeof(text));
    M66_CheckResult("SIM ICCID", status);
