static M66_Event last_event;

static const char *M66_StatusName(M66_Status status)
{
    switch (status) {
    case M66_OK:             return "OK";
    case M66_E_ARG:          return "Invalid argument";
    case M66_E_BUSY:         return "Busy";
    case M66_E_TIMEOUT:      return "Timeout";
    case M66_E_MODEM:        return "Modem error";
    case M66_E_QUEUE_FULL:   return "Queue full";
    case M66_E_UART:         return "UART error";
    case M66_E_PARSE:        return "Parse error";
    case M66_E_NOT_READY:    return "Not ready";
    case M66_E_UNSUPPORTED:  return "Unsupported";
    case M66_E_OVERFLOW:     return "Overflow";
    case M66_E_NETWORK:      return "Network error";
    case M66_E_STATE:        return "Invalid state";
    default:                 return "Unknown status";
    }
}

static void M66_CheckResult(const char *operation, M66_Status status)
{
    /* Replace printf with your UART logger, SWO, RTT or debugger logger. */
    printf("[M66] %-28s : %s (%d)\r\n",
           operation, M66_StatusName(status), (int)status);
}

static void M66_OnEvent(const M66_Event *event, void *user)
{
    (void)user;

    if (event == NULL) {
        return;
    }

    /* Keep callback short. Do not run blocking AT commands from this callback. */
    last_event = *event;

    switch (event->type) {
    case M66_EV_READY:
        m66_ready_event = 1U;
        break;

    case M66_EV_SMS_NOTIFICATION:
    case M66_EV_SMS_RECEIVED:
        m66_sms_event = 1U;
        break;

    case M66_EV_SOCKET_DATA:
        m66_socket_data_event = 1U;
        break;

    case M66_EV_HTTP_COMPLETE:
        m66_http_event = 1U;
        break;

    case M66_EV_USSD:
        m66_ussd_event = 1U;
        break;

    default:
        break;
    }

    printf("[M66 EVENT] type=%d code=%ld len=%u text=\"%s\"\r\n",
           (int)event->type,
           (long)event->code,
           (unsigned int)event->len,
           event->text);
}

/* ------------------------------------------------------------------------- */
/* 1. Initialization: choose UART and RX mode here.                           */
/* ------------------------------------------------------------------------- */
M66_Status Example_M66_Init(void)
{
    M66_Config config;

    memset(&config, 0, sizeof(config));
    config.huart = &huart2;                 /* Change to huart1/huart3/etc. */
    config.hdma_rx = NULL;                  /* NULL uses huart->hdmarx. */
    config.hdma_tx = NULL;                  /* NULL uses huart->hdmatx. */
    config.rx_mode = M66_RX_CIRCULAR;
    config.rx_dma_size = M66_RX_DMA_SIZE;
    config.tx_queue_size = M66_TX_QUEUE_SIZE;
    config.default_timeout_ms = 3000U;
    config.prompt_timeout_ms = 5000U;
    config.enable_rx_half_callback = 1U;

    M66_Status status = M66_Init(&hm66, &config);
    if (status == M66_OK) {
        M66_RegisterCallback(&hm66, M66_OnEvent, NULL);
    }

    M66_CheckResult("Initialize modem driver", status);
    return status;
}

/* Call this continuously from while (1), not just once at startup. */
void Example_M66_Process(void)
{
    M66_Process(&hm66);
}

